#!/usr/bin/env python3
"""Generate the closed case16594 actual endpoint-pair fixture.

The output is DEVELOPMENT / NON-RELEASE data.  The generator accepts only the
pinned 875-row native-input export and emits the exact 2^40 floor encodings of
the first and fourth lower box coordinates.  Candle still evaluates the
resulting products; this generator supplies no verdict or theorem evidence.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
from pathlib import Path


EXPECTED_INPUT_SHA256 = (
    "236c4ffa1773b92c80584defa24beeddfb20b59811bc287a4f4770da87ac8e80"
)
SCALE = 1 << 40
WORD_LIMIT = 1 << 64


def floor_scaled(value: Fraction) -> int:
    return (value.numerator * SCALE) // value.denominator


def load_pairs(path: Path) -> list[tuple[int, int]]:
    payload = path.read_bytes()
    actual_hash = hashlib.sha256(payload).hexdigest()
    if actual_hash != EXPECTED_INPUT_SHA256:
        raise ValueError(
            f"case16594 input identity drift: {actual_hash}"
        )
    rows = payload.decode("ascii").splitlines()
    if len(rows) != 875:
        raise ValueError(f"case16594 row count drift: {len(rows)}")

    pairs: list[tuple[int, int]] = []
    for expected_index, row in enumerate(rows):
        fields = row.split("\t")
        if len(fields) != 5 or int(fields[0]) != expected_index:
            raise ValueError(f"malformed case16594 row {expected_index}")
        lower = [Fraction(value) for value in fields[3].split(",")]
        upper = [Fraction(value) for value in fields[4].split(",")]
        if len(lower) != 6 or len(upper) != 6:
            raise ValueError(f"box width drift at row {expected_index}")
        if any(lo > hi for lo, hi in zip(lower, upper)):
            raise ValueError(f"reversed box at row {expected_index}")
        left = floor_scaled(lower[0])
        right = floor_scaled(lower[3])
        if not (0 <= left < WORD_LIMIT and 0 <= right < WORD_LIMIT):
            raise ValueError(f"endpoint width/sign drift at row {expected_index}")
        pairs.append((left, right))
    return pairs


def expected_digest(pairs: list[tuple[int, int]]) -> int:
    digest = 0
    for left, right in pairs:
        quotient = (left * right) // SCALE
        high, low = divmod(quotient, WORD_LIMIT)
        digest ^= high ^ low
    return digest


def render(pairs: list[tuple[int, int]]) -> str:
    digest = expected_digest(pairs)
    pair_lines = []
    for index, (left, right) in enumerate(pairs):
        suffix = ";" if index + 1 != len(pairs) else ""
        pair_lines.append(f"    ({left}w,{right}w){suffix}")
    data = "\n".join(pair_lines)
    return f'''(*
  GENERATED by generate_case16594_actual_data.py.
  Source jobs SHA-256: {EXPECTED_INPUT_SHA256}
  DEVELOPMENT / NON-RELEASE / NON-AUTHORITATIVE.
*)
Theory compute_boundedCase16594ActualData
Ancestors
  compute_bounded
Libs
  bossLib wordsLib

Definition bounded_case16594_actual_lower_x1_x4_pairs_def:
  bounded_case16594_actual_lower_x1_x4_pairs :
      (word64 # word64) list =
  [
{data}
  ]
End

Theorem bounded_case16594_actual_lower_x1_x4_pairs_length:
  LENGTH bounded_case16594_actual_lower_x1_x4_pairs = 875
Proof
  EVAL_TAC
QED

Definition bounded_case16594_actual_lower_x1_x4_digest_def:
  bounded_case16594_actual_lower_x1_x4_digest =
    bounded_word64_mul_shift_floor40_pairs
      bounded_case16594_actual_lower_x1_x4_pairs 0w
End

Theorem bounded_case16594_actual_lower_x1_x4_digest_value:
  bounded_case16594_actual_lower_x1_x4_digest = {digest}w
Proof
  EVAL_TAC >> wordsLib.WORD_EVAL_TAC
QED

Definition bounded_case16594_actual_lower_x1_x4_ok_def:
  bounded_case16594_actual_lower_x1_x4_ok (u:unit) =
    (LENGTH bounded_case16594_actual_lower_x1_x4_pairs = 875 ∧
     bounded_case16594_actual_lower_x1_x4_digest = {digest}w)
End

val _ = export_theory ();
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("jobs", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    pairs = load_pairs(args.jobs)
    args.output.write_text(render(pairs), encoding="utf-8")


if __name__ == "__main__":
    main()
