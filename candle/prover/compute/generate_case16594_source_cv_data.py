#!/usr/bin/env python3
"""Generate the exact case-16594 cv source-descriptor theorem.

The decoder and the theorem, not this generator, are proof authority.  The
generator is deliberately pinned to the same source hash as the independently
generated typed program and emits no accepted Boolean or numerical result.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from generate_case16594_program_data import (
    EXPECTED_PROGRAM_SHA256,
    Node,
    Parser,
)


def render_cv(node: Node) -> str:
    if isinstance(node, int):
        return f"Num {node}"
    left, right = node
    return f"Pair ({render_cv(left)}) ({render_cv(right)})"


def render(node: Node) -> str:
    return f'''(*
  GENERATED by generate_case16594_source_cv_data.py.
  Source program SHA-256: {EXPECTED_PROGRAM_SHA256}
  DEVELOPMENT / NON-RELEASE / NON-AUTHORITATIVE.
*)
Theory compute_boundedCase16594SourceCVData
Ancestors
  compute_boundedAnalyticProgramCV
Libs
  bossLib preamble

Definition bounded_case16594_source_program_cv_def:
  bounded_case16594_source_program_cv = {render_cv(node)}
End

Theorem bounded_case16594_source_program_cv_decodes:
  bounded_analytic_program_of_cv bounded_case16594_source_program_cv =
    SOME bounded_case16594_program
Proof
  EVAL_TAC
QED

val _ = export_theory ();
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("program", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    payload = args.program.read_bytes()
    actual_hash = hashlib.sha256(payload).hexdigest()
    if actual_hash != EXPECTED_PROGRAM_SHA256:
        raise ValueError(f"case16594 program identity drift: {actual_hash}")
    text = payload.decode("ascii")
    if not text.endswith("\n") or "\n" in text[:-1]:
        raise ValueError("case16594 program must be one newline-terminated line")
    node = Parser(text[:-1]).parse()
    args.output.write_text(render(node), encoding="utf-8")


if __name__ == "__main__":
    main()
